//! Micro-CNN screen classifier: a compiled static forward-pass engine with
//! zero dependencies (`std` only).
//!
//! Architecture: two 128x128 RGB streams in, full frame plus center-half
//! crop at 2x content magnification. Conv2D with 16 filters over R, G, B
//! and a Y-coordinate plane, pad 1, shared across streams. ReLU, MaxPool
//! 8x8, concatenated dense, argmax over nine screen classes. About 74,329
//! parameters (~297 KB), tens of milliseconds per frame in release.
//!
//! The CNN is the whole classifier: every frame goes through it, no pixel
//! gates in front. Class count and label order are fixed by [`ScreenClass`]
//! (must match the trainer).
//!
//! Weights are baked in at compile time from `artifacts/weights.bin`
//! (little-endian f32, layout below) via [`WEIGHTS`]. That file is
//! generated by the dev-time trainer (`examples/train_cnn.rs`, pure Rust,
//! no ML libraries) from the labeled corpus in `tests/fixtures/` plus
//! synthetic frames — see the example for the label map and regeneration
//! recipe. The binary never trains; it only evaluates.
//!
//! No `unsafe`: the byte blob is decoded to f32 once with
//! [`f32::from_le_bytes`] behind a [`LazyLock`].

use std::sync::LazyLock;

/// Input frame edge length: every screendump is resampled to this square
/// before inference, so any source resolution feeds the same descriptor.
pub const GRID: usize = 128;
/// Convolution filters in the single conv layer. Sixteen leaves room for
/// near-duplicate layouts (installer progress vs requirements block) to
/// own separate filters: fewer than the frames could memorize.
pub const N_FILTERS: usize = 16;
/// Convolution kernel edge length (square, odd, stride 1, pad 1).
pub const KERNEL: usize = 3;
/// Model input channels: R, G, B plus a static vertical-coordinate map
/// (CoordConv: -1.0 top row to +1.0 bottom row). Lets 3x3 kernels learn
/// position-dependent features ("spinner under a logo" vs "spinner under
/// setup text") instead of pure texture. RGB captures stay 3-channel;
/// the coordinate plane is synthesized at normalize time.
pub const INPUT_CHANNELS: usize = 4;
/// Max-pool window edge length (square, stride equals window). Eight
/// collapses each filter to a GRID/8 thumbnail: position within fine
/// cells survives, exact pixels do not.
pub const POOL: usize = 8;
/// Pooled feature edge length per filter (`GRID / POOL`).
pub const POOLED: usize = GRID / POOL;
/// Pooled features per filter (`POOLED * POOLED`).
pub const POOL_FEATURES: usize = POOLED * POOLED;
/// Flattened dense inputs (`N_FILTERS * POOL_FEATURES`).
pub const DENSE_INPUTS: usize = N_FILTERS * POOL_FEATURES;
/// Streams fused per frame: the full view plus the center-half crop (2x
/// content magnification where window interiors live, while title bars
/// and surrounds fall outside).
pub const STREAMS: usize = 2;
/// Flattened dense inputs across all streams (`STREAMS * DENSE_INPUTS`):
/// the two pooled thumbnails concatenate before the dense layer.
pub const DENSE_TOTAL: usize = STREAMS * DENSE_INPUTS;

/// Raw trained weights (little-endian f32), baked into the binary.
static WEIGHT_BYTES: &[u8] = include_bytes!("../artifacts/weights.bin");

/// Weight layout inside [`WEIGHT_BYTES`]: conv weights
/// `[N_FILTERS, INPUT_CHANNELS, KERNEL, KERNEL]` (shared across streams),
/// conv bias `[N_FILTERS]`, dense weights `[N_CLASSES, DENSE_TOTAL]`
/// (full-stream thumbnail first, crop thumbnail second), dense bias
/// `[N_CLASSES]`.
pub const N_WEIGHTS: usize =
    N_FILTERS * INPUT_CHANNELS * KERNEL * KERNEL + N_FILTERS + N_CLASSES * DENSE_TOTAL + N_CLASSES;

/// Number of screen classes (dense outputs).
pub const N_CLASSES: usize = 9;

/// Decoded weights (f32), parsed once on first use.
static WEIGHTS: LazyLock<Box<[f32]>> = LazyLock::new(|| {
    assert_eq!(
        WEIGHT_BYTES.len(),
        N_WEIGHTS * 4,
        "artifacts/weights.bin corrupt: want {} bytes, have {} (regenerate with `cargo run --release --example train_screen_cnn`)",
        N_WEIGHTS * 4,
        WEIGHT_BYTES.len()
    );
    WEIGHT_BYTES
        .as_chunks::<4>()
        .0
        .iter()
        .map(|b| f32::from_le_bytes(*b))
        .collect()
});

/// Screen classes, in logit order (must match the trainer's label map).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ScreenClass {
    /// Nothing on screen (pure black).
    Dark,
    /// Bare color field, no UI.
    FlatField,
    /// UEFI shell prompt (no bootable device).
    ErrorShell,
    /// Windows Setup / installer / OOBE progress screens.
    InstallerStep,
    /// Windows Recovery screens (WinRE menus and failure text).
    ErrorRecovery,
    /// Error UI needing input: modal failure dialogs and bugcheck screens.
    /// One class on purpose — the operational response is identical, and
    /// neither has enough captures to stand alone.
    ErrorScreen,
    /// Anything else: lock screen, gradients. (No desktop ever appears in
    /// this flow, so the lock screen stands in as the class name for the
    /// remaining miscellaneous bucket.)
    Lockscreen,
    /// Firmware boot art: TianoCore splash, boot logos. Transient screens
    /// between firmware handoff and the OS, visually distinct from both
    /// text consoles and OS screens.
    FirmwareBoot,
    /// First-boot OOBE transitionals ("Just a moment", logo splash,
    /// "Welcome"): post-install, pre-logon. Progress, never errors.
    OobeStep,
}

/// Logit index to class. The single source of truth for index order:
/// [`predict_two_stream`] returns through this table, and the roundtrip
/// test below fails the build if the enum order ever drifts from it again.
/// Public so the trainer's stats lines print variant names (`{:?}`), not
/// bare indices no one can cross-correlate mid-run.
pub const BY_INDEX: [ScreenClass; N_CLASSES] = [
    ScreenClass::Dark,
    ScreenClass::FlatField,
    ScreenClass::ErrorShell,
    ScreenClass::InstallerStep,
    ScreenClass::ErrorRecovery,
    ScreenClass::ErrorScreen,
    ScreenClass::Lockscreen,
    ScreenClass::FirmwareBoot,
    ScreenClass::OobeStep,
];

/// Center-half crop region (x0, y0, x1, y1) in source pixels: the middle
/// quarter of the frame by area, where installer/error content lives.
/// Shared with the trainer so both sides cut the same pixels.
pub fn crop_region(src_w: usize, src_h: usize) -> (usize, usize, usize, usize) {
    let x0 = src_w / 4;
    let y0 = src_h / 4;
    let x1 = (x0 + src_w / 2).min(src_w).max(x0 + 1);
    let y1 = (y0 + src_h / 2).min(src_h).max(y0 + 1);
    (x0, y0, x1, y1)
}

/// Brightest-pixel downsample of a source region to GRID x GRID.
/// Full-frame `downsample_to_grid_rgb` is this over the whole frame.
/// Each output pixel takes the brightest source pixel in its cell (per
/// channel) rather than the nearest neighbor: thin white text and
/// spinner arcs on black survive the shrink instead of sampling out
/// of existence.
pub fn downsample_region_to_grid_rgb(
    src: &[u8],
    src_w: usize,
    src_h: usize,
    x0: usize,
    y0: usize,
    x1: usize,
    y1: usize,
) -> [u8; 3 * GRID * GRID] {
    assert_eq!(src.len(), src_w * src_h * 3, "downsample size mismatch");
    assert!(
        x0 < x1 && x1 <= src_w && y0 < y1 && y1 <= src_h,
        "crop region out of bounds"
    );
    let (rw, rh) = (x1 - x0, y1 - y0);
    let mut out = [0u8; 3 * GRID * GRID];
    for y in 0..GRID {
        let sy0 = y0 + y * rh / GRID;
        let sy1 = (y0 + (y + 1) * rh / GRID).max(sy0 + 1).min(y1);
        for x in 0..GRID {
            let sx0 = x0 + x * rw / GRID;
            let sx1 = (x0 + (x + 1) * rw / GRID).max(sx0 + 1).min(x1);
            let mut best = [0u8; 3];
            for sy in sy0..sy1 {
                for sx in sx0..sx1 {
                    let s = (sy * src_w + sx) * 3;
                    for c in 0..3 {
                        if src[s + c] > best[c] {
                            best[c] = src[s + c];
                        }
                    }
                }
            }
            let d = (y * GRID + x) * 3;
            out[d..d + 3].copy_from_slice(&best);
        }
    }
    out
}

/// Brightest-pixel downsample of full-resolution RGB to GRID x GRID.
/// `src` is row-major `src_w` x `src_h` RGB; resolution-independent, so any
/// screendump size feeds the same descriptor.
pub fn downsample_to_grid_rgb(src: &[u8], src_w: usize, src_h: usize) -> [u8; 3 * GRID * GRID] {
    downsample_region_to_grid_rgb(src, src_w, src_h, 0, 0, src_w, src_h)
}

/// Micro-CNN forward pass over two GRID x GRID RGB views: the full frame
/// plus its center-half crop. Shared conv filters run each stream, the
/// pooled thumbnails concatenate, one dense layer decides. Pure function
/// of the inputs and the baked weights: deterministic bit-for-bit.
pub fn predict_two_stream(
    full: &[u8; 3 * GRID * GRID],
    crop: &[u8; 3 * GRID * GRID],
) -> ScreenClass {
    const GRID2: usize = GRID * GRID;
    const KERNEL2: usize = KERNEL * KERNEL;
    let w = &WEIGHTS[..];
    let (conv_w, rest) = w.split_at(N_FILTERS * INPUT_CHANNELS * KERNEL2);
    let (conv_b, rest) = rest.split_at(N_FILTERS);
    let (dense_w, rest) = rest.split_at(N_CLASSES * DENSE_TOTAL);
    let (dense_b, _) = rest.split_at(N_CLASSES);
    let pad = KERNEL / 2;

    let mut pool_out = [0.0f32; DENSE_TOTAL];
    for (s, rgb) in [full, crop].iter().enumerate() {
        // 1. Normalize u8 [0, 255] to f32 [0, 1], CHW layout, plus the
        // static Y-coordinate plane (CoordConv anchor).
        let mut chw = [0.0f32; INPUT_CHANNELS * GRID * GRID];
        for c in 0..3 {
            for i in 0..GRID2 {
                chw[c * GRID2 + i] = rgb[i * 3 + c] as f32 / 255.0;
            }
        }
        for r in 0..GRID {
            let y_coord = (r as f32 / (GRID - 1) as f32) * 2.0 - 1.0;
            for c in 0..GRID {
                chw[3 * GRID2 + r * GRID + c] = y_coord;
            }
        }

        // 2. Conv2D + ReLU (pad 1 keeps GRID x GRID).
        let mut conv_out = [0.0f32; N_FILTERS * GRID * GRID];
        for oc in 0..N_FILTERS {
            let b = conv_b[oc];
            for r in 0..GRID {
                for c in 0..GRID {
                    let mut sum = b;
                    for ic in 0..INPUT_CHANNELS {
                        for kr in 0..KERNEL {
                            let nr = r as isize + kr as isize - pad as isize;
                            if nr < 0 || nr >= GRID as isize {
                                continue;
                            }
                            for kc in 0..KERNEL {
                                let nc = c as isize + kc as isize - pad as isize;
                                if nc < 0 || nc >= GRID as isize {
                                    continue;
                                }
                                let in_idx = ic * GRID2 + (nr as usize) * GRID + (nc as usize);
                                let w_idx =
                                    oc * INPUT_CHANNELS * KERNEL2 + ic * KERNEL2 + kr * KERNEL + kc;
                                sum += chw[in_idx] * conv_w[w_idx];
                            }
                        }
                    }
                    conv_out[oc * GRID2 + r * GRID + c] = sum.max(0.0);
                }
            }
        }

        // 3. MaxPool (POOL x POOL, stride POOL) into this stream's half.
        let base = s * DENSE_INPUTS;
        for ch in 0..N_FILTERS {
            for r in 0..POOLED {
                for c in 0..POOLED {
                    let mut max_v = f32::NEG_INFINITY;
                    for kr in 0..POOL {
                        for kc in 0..POOL {
                            let idx = ch * GRID2 + (r * POOL + kr) * GRID + (c * POOL + kc);
                            if conv_out[idx] > max_v {
                                max_v = conv_out[idx];
                            }
                        }
                    }
                    pool_out[base + ch * POOL_FEATURES + r * POOLED + c] = max_v;
                }
            }
        }
    }

    // 4. Dense + argmax.
    let mut logits = [0.0f32; N_CLASSES];
    for o in 0..N_CLASSES {
        let mut sum = dense_b[o];
        let row = &dense_w[o * DENSE_TOTAL..(o + 1) * DENSE_TOTAL];
        for i in 0..DENSE_TOTAL {
            sum += pool_out[i] * row[i];
        }
        logits[o] = sum;
    }
    let mut best = 0;
    let mut best_val = logits[0];
    for (i, &v) in logits.iter().enumerate().skip(1) {
        if v > best_val {
            best_val = v;
            best = i;
        }
    }
    BY_INDEX[best]
}

/// Classify a full-resolution RGB frame: full view plus center-half crop,
/// then the two-stream predict.
pub fn predict_full(rgb: &[u8], width: u32) -> ScreenClass {
    let height = rgb.len() / 3 / width as usize;
    assert_eq!(
        rgb.len(),
        width as usize * height * 3,
        "predict_full size mismatch"
    );
    let w = width as usize;
    let full = downsample_to_grid_rgb(rgb, w, height);
    let (x0, y0, x1, y1) = crop_region(w, height);
    let crop = downsample_region_to_grid_rgb(rgb, w, height, x0, y0, x1, y1);
    predict_two_stream(&full, &crop)
}

/// Load an 8-bit PNG from disk and expand any color type to raw RGB.
/// Shared by the trainer (`examples/train_cnn.rs`) and the classifier
/// tests over `tests/fixtures/`.
pub fn load_rgb_8bit(path: &str) -> (Vec<u8>, u32, u32) {
    let file = std::fs::File::open(path).unwrap_or_else(|e| panic!("open fixture {path}: {e}"));
    let decoder = png::Decoder::new(file);
    let mut reader = decoder
        .read_info()
        .unwrap_or_else(|e| panic!("read fixture {path}: {e}"));
    let mut buf = vec![0; reader.output_buffer_size()];
    let frame = reader
        .next_frame(&mut buf)
        .unwrap_or_else(|e| panic!("decode fixture {path}: {e}"));
    assert_eq!(
        frame.bit_depth,
        png::BitDepth::Eight,
        "fixture {path} is not 8-bit"
    );
    let (w, h) = (frame.width, frame.height);
    let px = &buf[..frame.buffer_size()];
    let rgb = match frame.color_type {
        png::ColorType::Rgb => px.to_vec(),
        png::ColorType::Rgba => px
            .as_chunks::<4>()
            .0
            .iter()
            .flat_map(|p| [p[0], p[1], p[2]])
            .collect(),
        png::ColorType::Grayscale => px.iter().flat_map(|&g| [g, g, g]).collect(),
        png::ColorType::GrayscaleAlpha => px
            .as_chunks::<2>()
            .0
            .iter()
            .flat_map(|p| [p[0], p[0], p[0]])
            .collect(),
        png::ColorType::Indexed => {
            let palette = reader
                .info()
                .palette
                .clone()
                .expect("indexed fixture has no palette");
            px.iter()
                .flat_map(|&i| {
                    let o = i as usize * 3;
                    [palette[o], palette[o + 1], palette[o + 2]]
                })
                .collect()
        }
    };
    (rgb, w, h)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn downsample_keeps_corners_at_grid() {
        // 2*GRID with distinct quadrants: brightest-pixel reduction must
        // land each quadrant's color in the matching output corner.
        const SRC: usize = 2 * GRID;
        let mut src = vec![0u8; SRC * SRC * 3];
        for y in 0..SRC {
            for x in 0..SRC {
                let i = (y * SRC + x) * 3;
                let c = match (y >= GRID, x >= GRID) {
                    (false, false) => [200, 0, 0],
                    (false, true) => [0, 200, 0],
                    (true, false) => [0, 0, 200],
                    (true, true) => [200, 200, 200],
                };
                src[i..i + 3].copy_from_slice(&c);
            }
        }
        let small = downsample_to_grid_rgb(&src, SRC, SRC);
        let at = |x: usize, y: usize| {
            let i = (y * GRID + x) * 3;
            [small[i], small[i + 1], small[i + 2]]
        };
        assert_eq!(at(0, 0), [200, 0, 0]);
        assert_eq!(at(GRID - 1, 0), [0, 200, 0]);
        assert_eq!(at(0, GRID - 1), [0, 0, 200]);
        assert_eq!(at(GRID - 1, GRID - 1), [200, 200, 200]);
    }

    #[test]
    fn crop_region_is_center_half() {
        // 800x600: center half by area, shared with the trainer.
        assert_eq!(crop_region(800, 600), (200, 150, 600, 450));
    }

    #[test]
    fn class_index_roundtrips() {
        // The rotation guard: enum discriminants must equal the logit table
        // positions, or training labels and inference mapping silently
        // rotate past each other (observed: lockscreen/firmware/oobe).
        for (i, c) in BY_INDEX.iter().enumerate() {
            assert_eq!(*c as usize, i, "BY_INDEX[{i}] is {c:?}");
        }
        assert_eq!(BY_INDEX.len(), N_CLASSES);
    }

    #[test]
    fn prediction_is_deterministic() {
        let (rgb, w, _) = load_rgb_8bit(&format!(
            "{}/tests/fixtures/win11-26300-en-us-retail/firmware-boot/tianocore-splash.png",
            env!("CARGO_MANIFEST_DIR")
        ));
        let a = predict_full(&rgb, w);
        let b = predict_full(&rgb, w);
        assert_eq!(a, b);
    }
}
